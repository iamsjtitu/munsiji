"""Iteration-10 export polish tests.

Verifies the rewritten `exports.py`:
- PDF uses the bundled FreeSans font (₹ glyph, no black boxes)
- PDF has Indian digit grouping, Dr/Cr suffix, In/Out for cash, page footer
- Long-note wrapping (no clipping)
- Excel: title block, styled header, real numeric cells with #,##0.00 format,
  freeze_panes below header, wider column B, Total row equals /statement,
  Closing text with ₹
- CSV: BOM + In/Out header for cash + Total row
- WhatsApp bot export path serves a valid ₹-bearing PDF
"""
from __future__ import annotations

