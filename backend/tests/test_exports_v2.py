# =============================================================== WhatsApp bot
class TestBotExport:
    def test_bot_pdf_export(self, api):
        """POST /api/whatsapp/simulate for a party ledger PDF export. AI may take ~20s."""
        r = api.post(f"{BASE_URL}/whatsapp/simulate",
                     json={"text": "Biki mill ka ledger pdf bhejo"}, timeout=30)
        assert r.status_code == 200, r.text
        data = r.json()
        files = data.get("files") or []
        # If the bot asks for format, reply 'pdf'
        if not files:
            reply = (data.get("reply") or "").lower()
            assert "pdf" in reply or "format" in reply or "kis" in reply, \
                f"unexpected reply with no files: {data}"
            time.sleep(1)
            r2 = api.post(f"{BASE_URL}/whatsapp/simulate", json={"text": "pdf"}, timeout=30)
            assert r2.status_code == 200, r2.text
            files = (r2.json().get("files") or [])
        assert files, f"no files[] in bot reply: {data}"
        url = files[0].get("url")
        assert url
        pdf = _download(url).content
        assert pdf[:4] == b"%PDF"
        assert b"FreeSans" in pdf
        text = _pdf_text(pdf)
        assert RUPEE in text
        assert BLACK_BOX not in text and REPLACEMENT not in text
