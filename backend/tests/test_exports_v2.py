class TestPdfLongNoteWrap:
    def test_long_note_wraps_without_error(self, api):
        rid = f"EXPTEST_{uuid.uuid4().hex[:6]}"
        # Party ledgers require a group_id — grab any existing group
        gs = api.get(f"{BASE_URL}/groups", timeout=15).json()
        gid = gs[0]["id"]
        cl = api.post(f"{BASE_URL}/ledgers",
                      json={"name": rid, "kind": "party", "group_id": gid}, timeout=15)
        assert cl.status_code in (200, 201), cl.text
        lid = cl.json()["id"]
        note = ("lambi note wali entry " * 9)[:180]  # ~180 chars, spaces regularly
        try:
            t = api.post(f"{BASE_URL}/transactions",
                         json={"ledger_id": lid, "direction": "debit", "amount": 111.0,
                               "note": note, "mode": "cash"}, timeout=15)
            assert t.status_code in (200, 201), t.text

            info = _export(api, lid, "pdf")
            r = _download(info["url"])
            assert r.status_code == 200
            text = _pdf_text(r.content)
            # First few words of the long note must appear (wrapping, not clipped)
            assert "lambi note wali entry" in text, "long note beginning not present in PDF"
            assert BLACK_BOX not in text and REPLACEMENT not in text
        finally:
            api.delete(f"{BASE_URL}/ledgers/{lid}", timeout=15)


# ======================================================================= Excel
class TestExcel:
    def test_party_excel(self, api, ledgers):
        info = _export(api, ledgers["party"]["id"], "excel")
        r = _download(info["url"])
        ct = r.headers.get("content-type", "")
        assert "spreadsheetml" in ct, f"content-type: {ct}"
        wb = load_workbook(io.BytesIO(r.content))
        ws = wb.active
        assert ws["A1"].value == f"{ledgers['party']['name']} — Ledger Statement"

        # Find header row
        head = None
        head_row_idx = None
        for row in ws.iter_rows(min_row=1, max_row=15, values_only=False):
            vals = [c.value for c in row]
            if vals[:5] == ["Date", "Particulars", f"Debit ({RUPEE})",
                            f"Credit ({RUPEE})", f"Balance ({RUPEE})"]:
                head = vals
                head_row_idx = row[0].row
                break
        assert head is not None, "header row not found in party Excel"

        # freeze_panes just below header
        fp = ws.freeze_panes
        assert fp is not None
        assert fp.endswith(str(head_row_idx + 1)), f"freeze_panes={fp}, expected below row {head_row_idx}"

        # col B width >= 40
        b_width = ws.column_dimensions["B"].width or 0
        assert b_width >= 40, f"col B width={b_width}"

        # find Total row and last row (Closing:)
        total_row = None
        closing_row = None
        for row in ws.iter_rows(min_row=head_row_idx + 1, values_only=False):
            b = row[1].value if len(row) > 1 else None
            if b == "Total":
                total_row = row
            if isinstance(b, str) and b.startswith("Closing:"):
                closing_row = row
        assert total_row is not None
        assert closing_row is not None
        assert RUPEE in closing_row[1].value

        # Total numeric cells + format
        for col_idx in (2, 3, 4):  # 0-based -> Debit/Credit/Balance columns are index 2,3,4
            cell = total_row[col_idx]
            assert isinstance(cell.value, (int, float)), f"Total col {col_idx} not numeric: {cell.value!r}"
            assert "#,##0.00" in (cell.number_format or ""), \
                f"Total col {col_idx} number_format={cell.number_format!r}"

        # Match to /statement
        st = api.get(f"{BASE_URL}/ledgers/{ledgers['party']['id']}/statement", timeout=15).json()
        assert round(total_row[2].value, 2) == round(st["total_debit"], 2)
        assert round(total_row[3].value, 2) == round(st["total_credit"], 2)
        assert round(total_row[4].value, 2) == round(st["closing_balance"], 2)

    def test_cash_excel_headers(self, api, ledgers):
        info = _export(api, ledgers["cash"]["id"], "excel")
        r = _download(info["url"])
        wb = load_workbook(io.BytesIO(r.content))
        ws = wb.active
        found = False
        for row in ws.iter_rows(min_row=1, max_row=15, values_only=True):
            if row[:5] == ("Date", "Particulars", f"In ({RUPEE})", f"Out ({RUPEE})", f"Balance ({RUPEE})"):
                found = True
                break
        assert found, "Cash excel header not In/Out"


