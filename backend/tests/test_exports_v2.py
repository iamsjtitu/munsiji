def _export(api, ledger_id: str, fmt: str) -> dict:
    r = api.post(f"{BASE_URL}/ledgers/{ledger_id}/export", json={"format": fmt}, timeout=30)
    assert r.status_code == 200, r.text
    return r.json()


def _download(url: str) -> requests.Response:
    r = requests.get(url, timeout=30)
    assert r.status_code == 200, f"download failed: {r.status_code} {r.text[:200]}"
    return r


# ================================================================== PDF party
class TestPdfParty:
    def test_party_pdf_has_rupee_and_freesans(self, api, ledgers):
        info = _export(api, ledgers["party"]["id"], "pdf")
        r = _download(info["url"])
        assert r.headers.get("content-type", "").startswith("application/pdf")
        assert r.content[:4] == b"%PDF", "not a PDF"
        # embedded FreeSans font (bundled TTF) - byte-level check on the PDF stream
        assert b"FreeSans" in r.content, "FreeSans font not embedded in PDF"

        text = _pdf_text(r.content)
        assert RUPEE in text, "rupee sign missing"
        for tok in ("Ledger Statement", "Opening Balance", "Total", ledgers["party"]["name"],
                    f"Debit ({RUPEE})", f"Credit ({RUPEE})", f"Balance ({RUPEE})",
                    f"Closing balance: {RUPEE}"):
            assert tok in text, f"missing token in PDF text: {tok!r}"

        # No black-box / replacement chars from missing glyph
        assert BLACK_BOX not in text
        assert REPLACEMENT not in text
        # Dr/Cr suffix on party balance somewhere
        assert (" Dr" in text) or (" Cr" in text) or ("(settled)" in text)


# ==================================================================== PDF cash
class TestPdfCash:
    def test_cash_pdf_headers_and_multipage_footer(self, api, ledgers):
        info = _export(api, ledgers["cash"]["id"], "pdf")
        r = _download(info["url"])
        assert r.headers.get("content-type", "").startswith("application/pdf")
        assert b"FreeSans" in r.content

        pages = _pdf_pages_text(r.content)
        text = "\n".join(pages)
        assert RUPEE in text
        assert BLACK_BOX not in text and REPLACEMENT not in text
        for tok in (f"In ({RUPEE})", f"Out ({RUPEE})", f"Balance ({RUPEE})", "cash in hand"):
            assert tok in text, f"cash PDF missing: {tok!r}"
        # Multi-page footer: Generated by Munsiji + Page N on page 1 and last page
        assert len(pages) >= 1
        for label, page_text in (("first", pages[0]), ("last", pages[-1])):
            assert "Generated by Munsiji" in page_text, f"footer missing on {label} page"
            assert re.search(r"Page \d+", page_text), f"page number missing on {label} page"

        # Indian-grouped numbers appear somewhere
        assert INR_GROUP_RE.search(text) or re.search(r"\b\d{1,3}(?:,\d{2,3})*\.\d{2}\b", text), \
            "no formatted numbers found"


